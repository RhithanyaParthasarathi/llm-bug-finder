#!/usr/bin/env python3
"""
Large-Scale Multi-Agent Benchmark Harvester for AgentPack.
Features:
- Robust network retry & reconnect for Hugging Face streaming.
- Context synthesis for class methods and auto-typing.
- Automated reproduction test generation.
- Structured JSON output with category classification.
"""
import argparse
import ast
import json
import os
import sys
import time
from datasets import load_dataset

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))
from agentpack_loader import is_node_modules_path, parse_patch_files, extract_file_sources_from_patch
from context_synthesizer import extract_all_changed_functions
from crosshair_runner import run_diffbehavior

sys.stdout.reconfigure(encoding='utf-8')


def classify_bug(old_src: str, new_src: str, raw_output: str, commit_msg: str) -> str:
    raw_lower = raw_output.lower()
    if "assertionerror" in raw_lower or "indexerror" in raw_lower or "keyerror" in raw_lower:
        return "Incorrect edge-case handling / Robustness crash"
    elif "typeerror" in raw_lower or "attributeerror" in raw_lower:
        return "Type-semantics bug"
    elif "math" in raw_lower or "domain error" in raw_lower:
        return "Incorrect edge-case handling"
    elif len(new_src.splitlines()) > len(old_src.splitlines()) * 2 or "loop" in commit_msg.lower():
        return "Wrong/suboptimal algorithm"
    else:
        return "Requirement misunderstanding / Missing branch logic"


def generate_reproduction_script(task_name: str, old_code: str, new_code: str, entry_point: str, output_path: str):
    script_content = f'''"""
Standalone Reproduction Test for Bug: {task_name}
Automatically generated by LLM-Diff-BugFinder.
"""
# --- Pre-diff Version ---
{old_code}

# --- Post-diff Version (AI Modified) ---
{new_code}
'''
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(script_content)


def stream_with_retry(max_retries=5):
    for attempt in range(max_retries):
        try:
            return load_dataset("nuprl/AgentPack", split="train", streaming=True)
        except Exception as e:
            print(f"[!] Network error ({e}), retrying in {2 ** attempt}s... (attempt {attempt+1}/{max_retries})")
            time.sleep(2 ** attempt)
    raise ConnectionError("Failed to connect to Hugging Face after multiple retries.")


def harvest(limit=15000, target_bugs=10, workdir="results/benchmark_workdir", benchmark_dir="results/benchmark"):
    os.makedirs(workdir, exist_ok=True)
    os.makedirs(benchmark_dir, exist_ok=True)
    benchmark_file = os.path.join(benchmark_dir, "benchmark_bugs.json")

    existing_bugs = []
    if os.path.exists(benchmark_file):
        with open(benchmark_file, "r", encoding="utf-8") as f:
            existing_bugs = json.load(f)
    seen_tasks = {b["task_name"] for b in existing_bugs}

    print(f"Starting Benchmark Harvester (Target: {target_bugs} bugs, Limit: {limit} commits)...")
    print(f"Existing verified bugs in benchmark: {len(existing_bugs)}")

    ds = stream_with_retry()

    scanned = 0
    candidates_tested = 0
    new_bugs_found = 0

    try:
        for r in ds:
            scanned += 1
            if scanned > limit or new_bugs_found >= target_bugs:
                break

            if scanned % 1000 == 0:
                print(f"Scanned {scanned} commits | Candidates tested: {candidates_tested} | Total bugs: {len(existing_bugs)}", flush=True)

            agent = r.get("agent", "")
            if agent not in ("Claude Code", "Cursor Agent"):
                continue

            patch = r.get("patch", "")
            file_entries = parse_patch_files(patch)
            if not file_entries or len(file_entries) != 1:
                continue

            old_p, new_p, is_new, is_del = file_entries[0]
            target = new_p if not is_del else old_p
            if not target.endswith(".py") or is_new or is_del or is_node_modules_path(target):
                continue

            extracted = extract_file_sources_from_patch(patch)
            if not extracted:
                continue
            file_path, old_src, new_src = extracted

            pairs = extract_all_changed_functions(old_src, new_src)
            if not pairs:
                continue

            repo_clean = r.get("repo", "unknown").replace("/", "__")
            sha_short = r.get("sha", "")[:8]

            for old_synth, new_synth in pairs:
                func_name = old_synth.name
                entry_point = f"{func_name}_wrapper" if old_synth.is_method else func_name
                task_name = f"{repo_clean}_{sha_short}_{func_name}"

                if task_name in seen_tasks:
                    continue

                candidates_tested += 1

                old_path = os.path.join(workdir, f"{task_name}_old.py")
                new_path = os.path.join(workdir, f"{task_name}_new.py")
                with open(old_path, "w", encoding="utf-8") as f:
                    f.write(old_synth.synthesized_source)
                with open(new_path, "w", encoding="utf-8") as f:
                    f.write(new_synth.synthesized_source)

                canon_mod = os.path.splitext(os.path.basename(old_path))[0]
                llm_mod = os.path.splitext(os.path.basename(new_path))[0]

                try:
                    res = run_diffbehavior(canon_mod, llm_mod, entry_point, cwd=workdir, per_condition_timeout=6)
                    if res.counterexample_found:
                        new_bugs_found += 1
                        category = classify_bug(old_synth.original_source, new_synth.original_source, res.raw_output, r.get("description", ""))
                        repro_path = os.path.join(benchmark_dir, f"repro_{task_name}.py")
                        generate_reproduction_script(task_name, old_synth.synthesized_source, new_synth.synthesized_source, entry_point, repro_path)

                        bug_record = {
                            "task_name": task_name,
                            "repo": r.get("repo"),
                            "sha": r.get("sha"),
                            "agent": agent,
                            "function_name": func_name,
                            "is_method": old_synth.is_method,
                            "category": category,
                            "commit_description": r.get("description", "")[:300],
                            "raw_counterexample": res.raw_output,
                            "repro_script": repro_path,
                        }
                        existing_bugs.append(bug_record)
                        seen_tasks.add(task_name)

                        with open(benchmark_file, "w", encoding="utf-8") as f:
                            json.dump(existing_bugs, f, indent=2)

                        print(f"\n[!] VERIFIED BUG #{len(existing_bugs)} FOUND: {task_name}")
                        print(f"    Category: {category}")
                        print(f"    Saved repro script: {repro_path}\n", flush=True)

                except Exception:
                    pass

    except Exception as e:
        print(f"[!] Stream interrupted with: {e}. Progress is safely saved in {benchmark_file}")

    print("\n" + "=" * 70)
    print(f"Harvester Summary:")
    print(f"  Total Commits Scanned:   {scanned}")
    print(f"  Total Functions Tested:  {candidates_tested}")
    print(f"  Total Verified Bugs:     {len(existing_bugs)} (Saved to {benchmark_file})")
    print("=" * 70)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--limit", type=int, default=15000)
    parser.add_argument("--target", type=int, default=10)
    args = parser.parse_args()
    harvest(limit=args.limit, target_bugs=args.target)
